<?php

namespace App\Domains\Banking\Services;

use App\Domains\Banking\Models\BankAccount;
use App\Domains\Banking\Models\ReceiptDestination;
use App\Domains\Banking\Models\ReceiptDestinationPayment;
use App\Domains\Banking\Models\Transaction;

class ReceiptAccountAllocationService
{
    public const CLIENT_ACCOUNT = 'Cliente';

    public const OFFICE_ACCOUNT = 'Mota e Silva Advogados';

    /** Keep an already assigned account even if it was renamed. Never guess among duplicates. */
    public function target(Transaction $receipt, string $kind): BankAccount
    {
        $name = $kind === 'client' ? self::CLIENT_ACCOUNT : self::OFFICE_ACCOUNT;
        $assignedId = $receipt->destinations()->where('kind', $kind)->value('repasse_account_id');
        $accounts = BankAccount::active()->where('type', 'repasse')->lockForUpdate();
        $matches = $assignedId
            ? $accounts->whereKey($assignedId)->get()
            : $accounts->get()->filter(fn ($account) => mb_strtolower(trim($account->name)) === mb_strtolower($name));
        if ($matches->count() !== 1) {
            throw new \DomainException($assignedId
                ? 'A conta de repasse vinculada a '.$name.' deve estar ativa e ser do tipo Repasse.'
                : 'Cadastre uma única conta chamada '.$name.' com o tipo Repasse e mantenha-a ativa antes de salvar a divisão.');
        }
        $account = $matches->first();
        if ($account->id === $receipt->bank_account_id) {
            throw new \DomainException('A conta do recebimento deve ser diferente das contas de repasse.');
        }

        return $account;
    }

    /** A negative entry in the virtual account reserves money without moving the bank balance. */
    public function sync(ReceiptDestination $part, BankAccount $target): void
    {
        $amount = (int) round((float) $part->amount * 100) - ($part->kind === 'client' ? $part->recoveredCents() + $part->offsetCents() : 0);
        $entry = $part->allocationTransaction;
        // Convert only the pair generated by the previous distribution flow.
        if ($entry && ($entry->bank_account_id !== $target->id || $entry->related_transaction_id)) {
            $this->remove($part);
            $entry = null;
        }
        $part->update(['repasse_account_id' => $target->id]);
        if ($amount <= 0) {
            $this->remove($part);

            return;
        }
        $data = [
            'type' => 'transfer', 'date' => $part->receipt->date->toDateString(), 'status' => 'settled',
            'amount' => '-'.$this->money($amount), 'bank_account_id' => $target->id,
            'source_type' => ReceiptDestination::class, 'source_id' => $part->id,
            'description' => mb_substr('Valor a repassar · '.$part->beneficiary, 0, 200),
            'notes' => 'Obrigação do recebimento #'.$part->receipt_id.'. O dinheiro permanece na conta bancária.',
        ];
        $transactions = app(TransactionService::class);
        if ($entry) {
            $transactions->updateGenerated($entry, $data);
        } else {
            $entry = $transactions->create($data);
            $part->update(['allocation_transaction_id' => $entry->id]);
        }
    }

    /** Credit the virtual account when an actual payment was recorded in a bank. */
    public function settle(ReceiptDestinationPayment $payment): void
    {
        $part = $payment->destination;
        if (! $part->repasse_account_id || $payment->settlement_transaction_id) {
            return;
        }
        $out = $payment->writ_income_id ? $payment->writIncome : $payment->transaction;
        if (! $out) {
            return;
        }
        $data = [
            'type' => 'transfer', 'date' => $out->date->toDateString(), 'status' => 'settled',
            'amount' => $payment->writ_income_id ? $payment->writ_amount : $this->money(abs((int) round((float) $out->amount * 100))),
            'bank_account_id' => $part->repasse_account_id,
            'description' => mb_substr(($payment->writ_income_id ? 'Requisitório adquirido · ' : 'Repasse realizado · ').$part->beneficiary, 0, 200),
            'source_type' => ReceiptDestinationPayment::class, 'source_id' => $payment->id,
            'notes' => 'Baixa da obrigação do recebimento #'.$part->receipt_id,
            'related_transaction_id' => $payment->transaction_created && $out->type === 'transfer' ? $out->id : null,
        ];
        $in = app(TransactionService::class)->create($data);
        $payment->update(['settlement_transaction_id' => $in->id]);
        if ($data['related_transaction_id']) {
            $out->update(['related_transaction_id' => $in->id]);
        }
    }

    public function remove(ReceiptDestination $part): void
    {
        if (! $part->allocation_transaction_id) {
            return;
        }
        $out = Transaction::findOrFail($part->allocation_transaction_id);
        $in = $out->related;
        $part->update(['allocation_transaction_id' => null]);
        if ($in) {
            app(TransactionService::class)->deleteGenerated($in);
        }
        app(TransactionService::class)->deleteGenerated($out);
        $part->unsetRelation('allocationTransaction');
    }

    public function clear(Transaction $receipt): void
    {
        foreach ($receipt->destinations()->whereNotNull('allocation_transaction_id')->lockForUpdate()->get() as $part) {
            $this->remove($part);
        }
    }

    private function money(int $cents): string
    {
        return intdiv($cents, 100).'.'.str_pad((string) ($cents % 100), 2, '0', STR_PAD_LEFT);
    }
}
